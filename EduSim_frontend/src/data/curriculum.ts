export type Topic = {
  name: string;
  hasSimulation?: boolean;
  simulationRoute?: string;
};

export type Chapter = {
  name: string;
  topics: Topic[];
};

export type Subject = {
  id: string;
  name: string;
  icon: string;
  description: string;
  chapters: number | Chapter[];
};

export type ClassInfo = {
  id: number;
  name: string;
  description: string;
  subjects: Subject[];
};

// --- Stream Types for Classes 11–12 ---
export type StreamId = "science-pcm" | "science-pcb" | "commerce" | "arts";

export type Stream = {
  id: StreamId | string;
  name: string;
  description: string;
  subjects: Subject[];
};

export type StreamClassInfo = {
  id: number;
  name: string;
  description: string;
  streams: Stream[];
};

// --- University Course Types ---
export type Course = {
  id: string;
  name: string;
  degree?: string;
  level: "undergraduate" | "postgraduate" | "diploma" | string;
  semester?: number | string;
  description: string;
  subjects: Subject[];
};

